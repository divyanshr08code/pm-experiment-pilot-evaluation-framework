"""Generate docs/RESULTS.md from what the code actually recorded. Never edit RESULTS.md by hand.

Run: python -m reporting.build_results
"""
import json

from analysis.common import REGISTER_DIR, ROOT

GROUPS = [("sql", "SQL layer"), ("pilot", "Pilot analysis, single seeded run"), ("ab", "A/B test"),
          ("validation", "Validation against planted truth"), ("truth_scores", "Scoring of checks against truth"),
          ("crosschecks", "Independent re-derivations")]


def fmt(value):
    if isinstance(value, str):
        return value
    if abs(value) >= 1000:
        return f"{value:,.1f}".rstrip("0").rstrip(".")
    if value != 0 and abs(value) < 0.001:
        return f"{value:.2e}"
    return f"{value:.4f}".rstrip("0").rstrip(".")


def load_all():
    return {name: json.loads((REGISTER_DIR / f"{name}.json").read_text()) for name, _ in GROUPS
            if (REGISTER_DIR / f"{name}.json").exists()}


def main():
    data = load_all()
    lines = ["# Results register (simulation study)", "",
             "All values below are simulated. This file is generated by `reporting/build_results.py` from values recorded",
             "as the code ran, and is not edited by hand. Source = the file and line that recorded the value.",
             "Seed 20261101 unless a row belongs to a replication loop, whose per-run seeds derive from it.",
             "Rebuild everything with `bash run_all.sh`.", ""]
    for name, title in GROUPS:
        if name not in data:
            continue
        items = data[name]
        lines += [f"## {title}", "", f"Command: `{items[0]['command']}`. Date: {items[0]['date']}. Seed: {items[0]['seed']}.", "",
                  "| ID | Value | Unit | What it is | Source |", "|---|---|---|---|---|"]
        for x in items:
            lines.append(f"| `{x['id']}` | {fmt(x['value'])} | {x['unit']} | {x['description']} | `{x['source']}` |")
        lines.append("")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("Wrote docs/RESULTS.md with", sum(len(v) for v in data.values()), "values")


if __name__ == "__main__":
    main()
